let lang = localStorage.getItem('savdocuments-lang') || (navigator.language.startsWith('it') ? 'it' : 'en');
export const getLang = () => lang;

export function setLang(l) {
    lang = l === 'it' ? 'it' : 'en';
    try {
        localStorage.setItem('savdocuments-lang', lang);
    } catch { /* private mode */
    }
    document.documentElement.lang = lang;
}

export const t = (k, v = {}) => (T[k] ? T[k][lang === 'it' ? 1 : 0] : k).replace(/\{(\w+)\}/g, (m, x) => v[x] ?? m);
export const has = (k) => !!T[k];

export function when(iso) {
    if (!iso) return '';
    const d = new Date(iso), s = (Date.now() - d) / 1000, rtf = new Intl.RelativeTimeFormat(lang, {numeric: 'auto'});
    if (s < 60) return rtf.format(0, 'minute');
    if (s < 3600) return rtf.format(-Math.floor(s / 60), 'minute');
    if (s < 86400) return rtf.format(-Math.floor(s / 3600), 'hour');
    if (s < 7 * 86400) return rtf.format(-Math.floor(s / 86400), 'day');
    return d.toLocaleDateString(lang, {
        day: 'numeric',
        month: 'short',
        year: d.getFullYear() === new Date().getFullYear() ? undefined : 'numeric'
    });
}
